// Real isolated product witness. Receipts/screenshots stay private; no fixed source values.
// node eval/integration/hardware.cjs URL NEW_PRIVATE_OUTPUT
const {chromium,expect}=require('../../dashboard/node_modules/@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
(async()=>{
  const url=process.argv[2]||'http://127.0.0.1:13111';
  const output=path.resolve(process.argv[3]||'private-eval/hardware-product/browser-01');
  await fs.mkdir(output); // preserve failed attempts
  const receipt={started:new Date().toISOString(),url,checks:[]};
  const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||'msedge',headless:true});
  const money=v=>new Intl.NumberFormat('en-US',{style:'currency',currency:'USD',minimumFractionDigits:0,maximumFractionDigits:2}).format(v);
  const number=v=>new Intl.NumberFormat('en-US',{maximumFractionDigits:2}).format(v);
  const range=b=>`${money(b.low)}–${money(b.high)}`;
  const pass=name=>{receipt.checks.push(name);console.log('PASS',name);};
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    page.setDefaultTimeout(30000);
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const response=page.waitForResponse(r=>r.url().includes('/api/cpu-hardware-scenario?'));
    await page.goto(url+'/#optimization');
    const summary=await(await response).json();
    assert.equal(summary.synthetic,false);
    receipt.scenario_id=summary.scenario_id;receipt.dataset_version=summary.dataset_version;
    const overview=page.getByRole('region',{name:'CFO decision overview'});
    const allocation=summary.allocations.find(a=>a.id==='memory_adjusted');
    await expect(overview).toContainText(range(allocation.success_net_reference_usd));
    await expect(overview).toContainText(range(allocation.failure_extra_reference_usd));
    await expect(overview).toContainText('full fitting population');
    await expect(overview).toContainText('not a confidence interval');
    pass('Overview distinguishes full-scope successful simulation and failed-replacement cost');
    await page.screenshot({path:path.join(output,'overview-desktop.png'),fullPage:true});
    await page.getByRole('button',{name:'Compare CPU pilot',exact:true}).click();
    const panel=page.getByRole('region',{name:'Documented CPU hardware scenario'});
    await expect(panel).toBeVisible();
    await expect(panel).toContainText(`${number(allocation.baseline_reduction_pct.low)}%–${number(allocation.baseline_reduction_pct.high)}%`);
    await expect(panel).toContainText(`${number(allocation.target_contribution_pct.low)}%–${number(allocation.target_contribution_pct.high)}%`);
    await expect(panel).toContainText(range(allocation.remaining_target_reference_usd));
    await expect(panel).toContainText('not the smaller pilot');
    pass('Model opens hardware view with baseline, target share and remaining gap');
    await panel.getByRole('combobox',{name:/CPU allocation/}).selectOption('whole_node');
    const whole=summary.allocations.find(a=>a.id==='whole_node');
    await expect(panel).toContainText(range(whole.success_net_reference_usd));
    await expect(overview).toContainText(range(whole.success_net_reference_usd));
    await panel.getByRole('combobox',{name:/CPU allocation/}).selectOption('memory_adjusted');
    pass('Allocation comparison updates panel and overview together');
    await panel.getByText('Inspect resource-fit evidence',{exact:true}).click();
    const firstLink=panel.getByRole('link',{name:/^Job /}).first();
    await expect(firstLink).toBeVisible();
    const first=await firstLink.getAttribute('href');
    assert.ok(first.includes('#data/jobs')&&first.includes('id='));
    await panel.getByRole('button',{name:'Next jobs'}).click();
    await expect(firstLink).not.toHaveAttribute('href',first);
    await panel.getByRole('combobox',{name:/Resource-fit group/}).selectOption('non_fit');
    await expect(panel).toContainText(`${number(summary.coverage.non_fitting_jobs)} jobs in this group.`);
    await panel.getByRole('combobox',{name:/Resource-fit group/}).selectOption('unresolved');
    await expect(panel).toContainText(`${number(summary.coverage.unresolved_jobs)} jobs in this group.`);
    pass('Evidence pagination and exclusion groups resolve source-job links');
    const download=page.waitForEvent('download');
    await panel.getByRole('button',{name:'Download hardware scenario'}).click();
    const exported=JSON.parse(await fs.readFile(await(await download).path(),'utf8'));
    assert.deepEqual(exported,{export_kind:'hardware-simulation-not-official-claims',...summary});
    pass('Scenario export preserves identity, assumptions and separation from claims');
    await page.getByRole('button',{name:'Manual small-pilot plan',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Should we run the CPU pilot?'})).toBeVisible();
    await expect(page.getByLabel('Pilot size (% of eligible GPU-hours)',{exact:true})).toHaveValue('5');
    await expect(page.getByLabel('CPU price ($/core-hour)',{exact:true})).toHaveValue('');
    await expect(overview).toContainText('Estimate pending');
    await expect(overview).not.toContainText(range(allocation.success_net_reference_usd));
    await page.getByRole('button',{name:'Documented hardware scenario',exact:true}).click();
    await expect(panel).toBeVisible();
    pass('Manual pilot stays unfilled and cannot inherit full-cohort benefit');
    await panel.scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,'model-desktop.png')});
    await page.setViewportSize({width:390,height:844});
    await panel.scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
    await page.screenshot({path:path.join(output,'model-mobile.png')});
    pass('Desktop/mobile model renders without page overflow');
    await page.route('**/api/cpu-hardware-scenario?*',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{message:'Witness unavailable'}})}));
    await page.reload();
    await expect(page.getByText(/Hardware scenario unavailable:/)).toBeVisible();
    await expect(overview).toContainText('Estimate pending');
    await expect(overview).not.toContainText(range(allocation.success_net_reference_usd));
    await page.unroute('**/api/cpu-hardware-scenario?*');
    await page.getByRole('button',{name:'Refresh source',exact:true}).click();
    await expect(overview).toContainText(range(allocation.success_net_reference_usd));
    pass('Feature outage is explicit; source refresh recovers without a false benefit');
    assert.deepEqual(errors,[]);
    receipt.status='PASS';
  }catch(error){receipt.status='FAIL';receipt.error=error.stack;throw error;}
  finally{receipt.finished=new Date().toISOString();await fs.writeFile(path.join(output,'receipt.json'),JSON.stringify(receipt,null,2));await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
